import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import {
  NOTICE, SITE, buildDatasets, catalogJsonLd, datasetDefinitions, latestReview, loadSource, root,
} from './lib/agent-data.mjs'

const source = await loadSource()
const data = buildDatasets(source)
const definitions = datasetDefinitions(data, source.occurrence, latestReview(source.speciesGuides))

// The /data page renders from this module, so the server HTML and the files agree.
const catalog = definitions.map(({ rows, ...definition }) => ({ ...definition, rowCount: rows.length }))
await writeFile(path.join(root, 'src', 'content', 'open-data.generated.js'),
  `// Generated by scripts/build-open-data.mjs.\nexport const openDatasets = ${JSON.stringify(catalog, null, 2)}\n\nexport const openDataJsonLd = ${JSON.stringify(catalogJsonLd(definitions))}\n`, 'utf8')

// Compact, edibility-free data for the read-only MCP server. Page bodies and ratings are not included.
const bySlug = Object.fromEntries(source.speciesGuides.map(guide => [guide.slug, guide]))
const species = source.speciesGuides.map(guide => {
  const entry = source.occurrence.fungi[guide.slug]
  const months = {}
  for (const hemisphere of ['north', 'south']) {
    const counts = entry?.months?.[hemisphere] ?? []
    const total = counts.reduce((sum, value) => sum + value, 0)
    months[hemisphere] = entry && total >= 30 && entry.observers >= 10 ? counts : null
  }
  return {
    slug: guide.slug, common_name: guide.common_name, latin_name: guide.latin_name,
    aliases: String(guide.aliases ?? '').split(',').map(item => item.trim()).filter(Boolean),
    taxon_id: guide.taxon_id, summary: guide.summary, season: guide.season, habitat: guide.habitat,
    difficulty: guide.difficulty, warning: guide.warning, last_reviewed: guide.last_updated || guide.last_reviewed,
    review_status: guide.reviewer,
    lookalikes: guide.lookalikes.map(item => ({
      name: item.name, slug: item.slug ?? null, severity: item.severity, check: item.check,
      url: item.slug && bySlug[item.slug] ? `${SITE}/learn/species/${item.slug}` : null,
    })),
    sources: guide.sources ?? [],
    months, people: entry?.observers ?? null, snapshot: source.occurrence.snapshot,
    url: `${SITE}/learn/species/${guide.slug}`,
  }
})
const regions = source.regions.map(region => ({ ...region, url: `${SITE}/regions/${region.slug}` }))
await mkdir(path.join(root, 'server'), { recursive: true })
await writeFile(path.join(root, 'server', 'agent-data.generated.json'), JSON.stringify({ notice: NOTICE, site: SITE, species, regions, snapshot: source.occurrence.snapshot }), 'utf8')
console.log(`Built ${definitions.length} open datasets and the MCP data file.`)
